// Function to parse the employees text
export function parseExactEmployees(): EmployeeRecord[] {
  const lines = RAW_EMPLOYEES_CSV.split('\n');
  let currentStore = '';
  const result: EmployeeRecord[] = [];

  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    const parts = line.split(',');
    const store = parts[0]?.trim();
    const emp = parts[1]?.trim();
    const month = parts[2]?.trim();
    const qty = parseFloat(parts[3]) || 0;
    const price = parseFloat(parts[4]) || 0;
    const upt = parseFloat(parts[5]) || 0;
    const atv = parseFloat(parts[6]) || 0;
    const utv = parseFloat(parts[7]) || 0;

    if (store === 'TOTAL' || emp === 'TOTAL' || line.startsWith('TOTAL')) continue;
    if (store) currentStore = store;
    if (!emp || !currentStore) continue;

    const trx = atv > 0 ? price / atv : 0;

    result.push({
      storeName: currentStore,
      employee: emp.toUpperCase().replace(/\s+/g, ' '),
      monthDate: '2026-08',
      soldQty: qty,
      extPrice: price,
      upt,
      atv,
      utv,
      trx: Math.round(trx),
    });
  }

  return result;
}

